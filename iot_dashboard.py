"""CICIoT2023 CSV prediction dashboard. Academic/demo use only."""
from pathlib import Path
import json
import re
import joblib
import numpy as np
import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parent
MODEL_PATH = ROOT / "models" / "iot_threat_model.joblib"
META_PATH = ROOT / "models" / "iot_model_metadata.json"
MAX_UPLOAD_MB = 100
MAX_ROWS = 100_000
BENIGN_NAMES = {"benigntraffic", "benign", "normal", "normaltraffic"}

st.set_page_config(page_title="IoT Cyber Threat Finder", page_icon="🛡️", layout="wide")
st.title("🛡️ IoT Cyber Threat Finder")
st.caption("CICIoT2023-based academic prototype • CSV inference, not live Wi-Fi capture")
st.warning("Predictions are model estimates, not confirmed incidents. This dashboard does not block devices or monitor the whole Wi-Fi network.")

if not MODEL_PATH.is_file() or not META_PATH.is_file():
    st.error("IoT model not found. First train it using the steps in README_IOT.md.")
    st.stop()

@st.cache_resource
def load_bundle(path, mtime):
    # Only load model files generated by your own training script. Never load untrusted joblib files.
    return joblib.load(path)

@st.cache_data
def load_metadata(path, mtime):
    return json.loads(Path(path).read_text(encoding="utf-8"))

try:
    bundle = load_bundle(str(MODEL_PATH), MODEL_PATH.stat().st_mtime)
    metadata = load_metadata(str(META_PATH), META_PATH.stat().st_mtime)
except Exception as exc:
    st.error(f"Could not load the locally trained model/metadata: {type(exc).__name__}: {exc}")
    st.stop()

m1, m2, m3, m4 = st.columns(4)
m1.metric("Dataset rows used", f"{metadata['rows_used']:,}")
m2.metric("Input features", str(metadata["feature_count"]))
m3.metric("Attack/benign labels", str(metadata["class_count"]))
m4.metric("Holdout accuracy", f"{metadata['multiclass_accuracy']:.1%}")
st.caption("Holdout metrics come from the model's training run and are not a guarantee of performance on new networks.")
st.divider()

st.subheader("Analyze a CSV")
upload = st.file_uploader("Upload a CSV with the same feature columns as the training dataset", type=["csv"])
if upload is not None:
    if upload.size > MAX_UPLOAD_MB * 1024 * 1024:
        st.error(f"File is too large. Maximum allowed size is {MAX_UPLOAD_MB} MB.")
        st.stop()
    try:
        df = pd.read_csv(upload, nrows=MAX_ROWS + 1, low_memory=False)
    except Exception as exc:
        st.error(f"CSV could not be read: {type(exc).__name__}: {exc}")
        st.stop()
    if len(df) > MAX_ROWS:
        st.error(f"CSV has more than {MAX_ROWS:,} rows. Please upload a smaller sample for this demo.")
        st.stop()
    expected = bundle["feature_columns"]
    has_label = "label" in df.columns
    actual_features = df.drop(columns=["label"], errors="ignore")
    missing = [c for c in expected if c not in actual_features.columns]
    extra = [c for c in actual_features.columns if c not in expected]
    if missing:
        st.error(f"Required feature columns are missing ({len(missing)}): {', '.join(missing[:12])}")
        st.stop()
    if extra:
        st.info(f"Ignoring {len(extra)} extra column(s), such as: {', '.join(extra[:8])}")
    X = actual_features[expected].copy()
    bad = X.select_dtypes(exclude="number").columns.tolist()
    if bad:
        st.error(f"These feature columns must be numeric: {', '.join(bad[:12])}")
        st.stop()
    X = X.replace([np.inf, -np.inf], np.nan)
    missing_counts = X.isna().sum()
    if missing_counts.sum():
        st.info(f"Missing/infinite values found in {int((missing_counts > 0).sum())} feature(s); using training-set medians for prediction.")
        X = X.fillna(pd.Series(bundle.get("medians", {}))).fillna(0)
    if X.empty:
        st.error("CSV contains no rows to predict.")
        st.stop()
    with st.spinner("Analyzing rows with the locally trained IoT model..."):
        pred = bundle["model"].predict(X)
        pred = pd.Series(pred, index=df.index, name="predicted_label")
        benign_names = set(bundle.get("benign_names", list(BENIGN_NAMES)))
        benign_mask = pred.astype(str).str.lower().isin(benign_names)
        if hasattr(bundle["model"], "predict_proba"):
            try:
                probs = bundle["model"].predict_proba(X)
                confidence = probs.max(axis=1) * 100
            except Exception:
                confidence = np.full(len(pred), np.nan)
        else:
            confidence = np.full(len(pred), np.nan)
    result = df.copy()
    result["predicted_label"] = pred.values
    result["traffic_class"] = np.where(benign_mask.values, "Benign", "Potential threat")
    result["model_confidence_pct"] = np.round(confidence, 2)
    c1, c2, c3 = st.columns(3)
    c1.metric("Rows analyzed", f"{len(result):,}")
    c2.metric("Predicted benign", f"{int(benign_mask.sum()):,}")
    c3.metric("Potential threats", f"{int((~benign_mask).sum()):,}")
    st.subheader("Predicted label distribution")
    st.bar_chart(result["predicted_label"].value_counts().head(20))
    if has_label:
        true_labels = df["label"].astype(str).str.lower().map(lambda s: re.sub(r"\s+", "", s))
        pred_labels = pred.astype(str).str.lower().map(lambda s: re.sub(r"\s+", "", s))
        # This is a descriptive comparison only; uploaded data may be training data.
        from sklearn.metrics import accuracy_score, f1_score
        st.subheader("Label comparison (only if labels are trustworthy)")
        st.metric("Accuracy on uploaded rows", f"{accuracy_score(true_labels, pred_labels):.1%}")
        st.caption("This is not an independent test metric if the uploaded rows were used for training.")
    st.subheader("Prediction preview")
    st.dataframe(result.head(200), use_container_width=True)
    csv_bytes = result.to_csv(index=False).encode("utf-8")
    st.download_button("Download predictions CSV", csv_bytes, file_name="iot_threat_predictions.csv", mime="text/csv")

with st.expander("Training evaluation details"):
    st.write(f"**Dataset:** {metadata['dataset']}")
    st.write(f"**Training rows:** {metadata['train_rows']:,} • **Test rows:** {metadata['test_rows']:,}")
    st.write(f"**Macro F1:** {metadata['macro_f1']:.3f} • **Weighted F1:** {metadata['weighted_f1']:.3f}")
    st.write("Per-class report is available in `models/iot_model_metadata.json`.")
    st.write("**Limitation:** CICIoT2023 is a benchmark dataset. This dashboard predicts CSV rows and does not yet collect live Wi-Fi traffic.")
